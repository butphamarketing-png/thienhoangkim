function svcSeo(
  slug: string,
  metaDescription: string,
  focusKeyphrase: string,
  keywords?: string,
): ArticleSeo {
  const displayTitle = slugToDisplayTitle(slug);
  return {
    ...DEFAULT_ARTICLE_SEO,
    metaTitle: buildMetaTitleFromSlug(slug),
    metaDescription,
    focusKeyphrase,
    keywords: keywords ?? focusKeyphrase,
    ogTitle: displayTitle,
    ogDescription: metaDescription,
  };
}

function newsSeo(
  slug: string,
  metaDescription: string,
  focusKeyphrase: string,
  keywords?: string,
  ogImage = intro,
): ArticleSeo {
  return buildNewsArticleSeo(slug, metaDescription, focusKeyphrase, keywords, ogImage);
}

function article(
  id: string,
  slug: string,
  title: string,
  date: string,
  description: string,
  body: string,
  image = intro,
  category = "Kiến thức",
  seo: ArticleSeo = { ...DEFAULT_ARTICLE_SEO },
): SiteArticle {
  return {
    id,
    slug,
    category,
    image,
    title,
    date,
    description,
    body,
    published: true,
    seo,
  };
}

